"""
Кэш на одну запись для источников сигнала.

## Зачем отдельный модуль на двадцать строк

Все три источника (SMC, FGI, деривативы) считают свои величины дважды за
прогон — в признаках и в атомах, по одним и тем же барам, — и все три
запоминали последний результат одинаковым куском кода:

    _CACHE["key"], _CACHE["value"] = key, value

Пара присваиваний **не атомарна**: GIL переключает потоки между ними.
Админка запускает до `ADMIN_MAX_CONCURRENT_RUNS` прогонов одновременно
через `BackgroundTasks`, то есть в разных потоках ОДНОГО процесса, и
перемежение «A пишет key_A → B пишет key_B → B пишет value_B → A пишет
value_A» оставляет в кэше **ключ монеты B со значением монеты A**.

Дальше это не падает, а тихо врёт: бары всех монет живут на одной
15-минутной сетке, индексы совпадают, и `a[name] = values[name]` в
`events._attach_sources` молча выравнивает чужие значения по совпавшим
timestamp — монета получает SMC-структуру или ОИ-квадранты соседки. Ровно
тот класс «тихо неверных данных», против которого выстроены инварианты 6 и
13 (аудит 2026-08-15, B2).

Починка — держать ключ и значение ОДНИМ объектом: запись одного значения в
dict под GIL атомарна, поэтому читатель видит либо старую пару целиком,
либо новую целиком, и рассогласованной пары не существует в принципе.
В CLI-прогонах (отдельный процесс на запуск) гонки нет — только в админке.
"""
from __future__ import annotations

from typing import Any


class SingleEntryCache:
    """
    Одна запись «ключ → значение», потокобезопасная на чтение и запись.

    Больше одной записи держать незачем: прогон обрабатывает монеты
    последовательно, вторая пара обращений вытесняет первую и ничего не
    удерживает в памяти сверх одного DataFrame.
    """

    __slots__ = ("_slot",)

    def __init__(self) -> None:
        # Значение слота — кортеж (ключ, значение) целиком, не два поля.
        self._slot: dict[str, tuple[Any, Any]] = {}

    def get(self, key: Any) -> Any | None:
        """Значение по ключу или None. Читает пару одним обращением."""
        entry = self._slot.get("entry")
        if entry is not None and entry[0] == key:
            return entry[1]
        return None

    def put(self, key: Any, value: Any) -> None:
        """Кладёт пару целиком — одним присваиванием."""
        self._slot["entry"] = (key, value)

    def clear(self) -> None:
        self._slot.clear()
