"""
Суррогатные данные: сколько «находок» порождает сама процедура.

## Зачем

Блочный бутстрап отвечает на вопрос «значим ли ЭТОТ эффект». Он не отвечает
на другой, и именно он остался открытым во всём проекте: **сколько эффектов
такого размера порождает сама процедура** — от признаков и разбиения до
критерия с его тремя условиями.

Вопрос перестал быть теоретическим 2026-08-19, когда квантильный регрессор
размаха стал первой конструкцией проекта с положительным вердиктом на
отложенной части (раздел 49). У пяти отрицательных результатов цена ошибки
низкая: анти-консервативный тест делает отрицательный вывод только надёжнее.
У одного положительного — наоборот, и проверить его нечем, кроме прогона того
же кода на данных, где предсказывать заведомо нечего.

ТЗ — `crypto-graph/docs/tz_wave_a_24-08-26.md`, задача S. Отличие от
негативных контролей, которые в проекте уже есть
(`test_false_positive_rate_is_near_nominal` и соседние): те подают шум в ОДНУ
функцию. Здесь суррогатом заменяются сами бары, и через конвейер проходит
всё — 32 признака, HAR-RV, сезонность, обучение, гейт.

## Два способа и чем они различаются

* **IAAFT** (iterative amplitude adjusted Fourier transform, Schreiber &
  Schmitz 1996). Сохраняет амплитудный спектр ряда доходностей и их
  маргинальное распределение, разрушая нелинейную структуру — то есть
  кластеризацию волатильности и суточный профиль. Самый жёсткий вариант: у
  такого суррогата не предсказывает НИЧЕГО, включая бенчмарк B2;
* **блочная перестановка** доходностей блоками в горизонт. Волатильность
  внутри блока сохраняется, на масштабах длиннее блока разрушается. Мягче:
  бенчмарк на нём частично работает, и это ближе к тому, как ошибается
  реальная процедура.

Гоняются оба. Совпадение ответов — довод; расхождение само по себе результат.

## Ловушка, из-за которой суррогат легко сделать нулёвкой не того

Признаки и цель считаются из ЧЕТЫРЁХ колонок OHLC плюс объёма, а любой
алгоритм суррогата работает с ОДНИМ рядом — доходностями закрытий. Способ
достроить остальное решает, что именно окажется нулёвкой, и здесь легко
ошибиться так, что тест станет не нулёвкой, а положительным контролем.

Первая версия этого модуля брала геометрию бара (`H/C`, `L/C`, `O/C`) у
донора **той же позиции**, чтобы сохранить суточный профиль размаха. Это
ошибка, и вот почему: цель `range_ratio` считается из `high`/`low`, то есть
она бы наследовала РЕАЛЬНУЮ кластеризацию волатильности, а часть признаков
(`atr_rank`, положение в диапазоне, доля нулевых баров) наследовала бы её же
— и суррогат стал бы данными, на которых предсказывать ЕСТЬ что. «Ложное
срабатывание» на таком материале не означало бы ничего.

Правильная конструкция: **суррогат — это перестановка целых баров**. Из
алгоритма извлекается перестановка π, по которой суррогатная доходность в
позиции `j` равна реальной доходности позиции `π(j)`, и вместе с доходностью
в позицию `j` переезжает весь бар донора — его геометрия, объём, число
сделок, объём тейкеров. Цена пересобирается кумулятивным произведением, чтобы
ряд остался непрерывным.

Тогда каждый бар суррогата — настоящий бар настоящего рынка, а разрушено
ровно одно: **их порядок во времени**. Значит разрушены и кластеризация
волатильности (для IAAFT), и привязка к часу суток, и любая связь между
конфигурацией и будущим. Предсказывать нечего ни бенчмарку, ни модели — а
это ровно то состояние, на котором и проверяется, сколько находок делает
процедура сама.
"""
from __future__ import annotations

import logging

import numpy as np
import pandas as pd

logger = logging.getLogger(__name__)

METHODS = ("iaaft", "block", "seasonal")


def log_returns(close: pd.Series) -> np.ndarray:
    """Логарифмические доходности. Первая строка теряется — так и надо."""
    values = np.asarray(close, dtype=float)
    return np.diff(np.log(values))


def iaaft_permutation(series: np.ndarray, rng: np.random.Generator,
                      iterations: int = 100) -> np.ndarray:
    """
    Перестановка π для IAAFT-суррогата: `суррогат[j] = series[π[j]]`.

    Наружу отдаётся именно перестановка, а не значения, и это принципиально:
    вместе с доходностью в новую позицию обязан переехать весь бар — его
    геометрия и объёмы (см. шапку модуля). Значения из перестановки
    получаются тривиально, обратно перестановка из значений — нет
    (одинаковые доходности встречаются).

    Алгоритм — итерация двух проекций: на множество рядов с заданным
    амплитудным спектром (замена амплитуд Фурье на целевые при сохранении
    фаз) и на множество рядов с заданным распределением (замена значений на
    отсортированные целевые по рангам). Сходится к пересечению, обычно за
    десятки итераций; выход — по стабилизации рангов.

    Почему не простая фазовая рандомизация (FT-суррогат): она сохраняет спектр
    точно, а распределение — нет, и на доходностях с их тяжёлыми хвостами
    результат заметно ближе к гауссову. Дальше по конвейеру это видно как
    изменившийся масштаб признаков, то есть нулёвка отличалась бы от данных не
    только тем, чем должна.
    """
    n = len(series)
    order = np.argsort(series)              # позиции значений по возрастанию
    target_sorted = series[order]
    target_amplitude = np.abs(np.fft.rfft(series))

    # Старт — случайная перестановка: то же распределение, спектр разрушен.
    permutation = rng.permutation(n)
    current = series[permutation]
    previous = None
    for _ in range(iterations):
        # Проекция 1: навязать целевой спектр, сохранив фазы текущего ряда.
        spectrum = np.fft.rfft(current)
        current = np.fft.irfft(target_amplitude * np.exp(1j * np.angle(spectrum)), n=n)
        # Проекция 2: навязать целевое распределение, сохранив порядок.
        ranks = np.argsort(np.argsort(current))
        permutation = order[ranks]
        current = target_sorted[ranks]
        if previous is not None and np.array_equal(ranks, previous):
            break
        previous = ranks
    return permutation


def block_permutation(n: int, block: int, rng: np.random.Generator) -> np.ndarray:
    """
    Перестановка непересекающихся блоков подряд идущих позиций.

    Блок берётся равным горизонту: внутри него волатильность и её форма
    сохраняются, между блоками — разрушаются. Хвост, не делящийся на блок,
    идёт последним блоком как есть; выбрасывать его нельзя — длина суррогата
    обязана совпадать с длиной ряда, иначе индекс времени разъедется.
    """
    block = max(1, min(int(block), n))
    starts = np.arange(0, n, block)
    order = rng.permutation(len(starts))
    pieces = [np.arange(s, min(s + block, n)) for s in starts]
    return np.concatenate([pieces[i] for i in order])[:n]


def seasonal_permutation(index: pd.DatetimeIndex, rng: np.random.Generator
                         ) -> np.ndarray:
    """
    Перестановка ВНУТРИ бинов «час дня × день недели».

    Нужна там, где разрушить надо всё, кроме сезонности. Час дня — крупнейший
    заведённый предиктор размаха в проекте (0.055–0.187 R² в одиночку, 47.5),
    и нулёвка, которая его тоже разрушает, отвечает на вопрос «есть ли на
    рынке сезонность» вместо заданного. Ровно на этой подмене был отозван
    гейт R деривативов (47.4).

    Бины считаются по времени бара-ПОЛУЧАТЕЛЯ: в позицию четверга-14:00
    приезжает бар какого-то другого четверга-14:00.
    """
    hours = index.hour.to_numpy()
    weekdays = index.dayofweek.to_numpy()
    key = weekdays * 24 + hours
    permutation = np.arange(len(index))
    for value in np.unique(key):
        positions = np.flatnonzero(key == value)
        permutation[positions] = rng.permutation(positions)
    return permutation


def surrogate_bars(base: pd.DataFrame, method: str, rng: np.random.Generator,
                   block: int = 96) -> pd.DataFrame:
    """
    Суррогатные бары: те же бары, переставленные во времени.

    Индекс, длина и набор колонок совпадают с исходными. В позицию `j`
    приезжает целиком бар донора `π(j)` — его геометрия (доли `O/C`, `H/C`,
    `L/C`), объём, число сделок, объём тейкеров, — а уровень цены
    пересобирается кумулятивным произведением доходностей, чтобы ряд остался
    непрерывным.

    Первый бар остаётся своим: доходность в него не ведёт ниоткуда.
    """
    if method not in METHODS:
        raise ValueError(f"Неизвестный способ {method!r}, известные: {METHODS}")

    close = np.asarray(base["close"], dtype=float)
    returns = log_returns(base["close"])
    n = len(returns)
    if n < 10:
        raise ValueError("Слишком короткий ряд для суррогата")

    if method == "iaaft":
        permutation = iaaft_permutation(returns, rng)
    elif method == "block":
        permutation = block_permutation(n, block, rng)
    else:
        # Сезонная: бины считаются по времени бара-получателя, а доходность
        # returns[i−1] ведёт В бар i, поэтому индекс сдвинут на единицу.
        permutation = seasonal_permutation(base.index[1:], rng)

    # Позиции доноров для БАРОВ: бар i получает доходность returns[i-1], то
    # есть донором бара i является бар permutation[i-1] + 1. Нулевой бар —
    # свой собственный.
    donors = np.empty(len(close), dtype=int)
    donors[0] = 0
    donors[1:] = permutation + 1

    synthetic = np.empty(len(close))
    synthetic[0] = close[0]
    synthetic[1:] = close[0] * np.exp(np.cumsum(returns[permutation]))

    out = base.iloc[donors].copy()
    out.index = base.index

    # Геометрия бара — долями от close донора, уровень — суррогатный.
    donor_close = close[donors]
    for column in ("open", "high", "low"):
        if column in base.columns:
            out[column] = np.asarray(out[column], dtype=float) / donor_close * synthetic
    out["close"] = synthetic

    # Порядок H ≥ max(O, C) ≥ min(O, C) ≥ L донор гарантирует не всегда:
    # доли считаются от close донора, а close бара стал другим. Восстанавливаем
    # явно — бар с low выше high уронит расчёт признаков там, где причину
    # искать будут в признаках.
    if {"high", "low"} <= set(out.columns):
        out["high"] = out[["open", "high", "close"]].max(axis=1)
        out["low"] = out[["open", "low", "close"]].min(axis=1)
    return out
