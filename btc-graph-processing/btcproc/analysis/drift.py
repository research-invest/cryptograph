"""
Дрейф распределения признаков: правда ли рынок меняется поквартально.

ТЗ — `crypto-graph/docs/tz_wave_a_24-08-26.md`, задача W; постановка —
`crypto-graph/docs/ideas_math_2026-08-18.md`, §2.5.

## Вопрос и почему он ставится именно так

Гипотеза владельца из `docs/task_regime_memory.md`: «рынок меняется каждый
квартал». Разбор той задачи показал, что квартальные модели состояний ломаются
механически (перенумерация `group_id`, несравнимость прогонов) — но сама
гипотеза при этом осталась непроверенной: сломалась реализация, а не идея.

Здесь она проверяется напрямую, без переобучения и без сноса графа.

Ключевое — **постановка вопроса**. «Отличается ли последний квартал от
истории» — вопрос бессодержательный: отличается всегда, любое окно любого
ряда отличается от любого другого, и при 300 тысячах наблюдений это
отличие будет значимым по любому тесту. Содержательный вопрос:

> отличается ли последний квартал от истории **сильнее, чем два случайных
> куска той же длины внутри самой истории**?

Именно так здесь и меряется. Нулёвка — расстояния между случайными
непересекающимися парами окон той же длины.

## Величина

`W₁` — расстояние Вассерштейна первого порядка между одномерными
распределениями, усреднённое по признакам. Для одномерного случая оно
считается точно и дёшево: это интеграл модуля разности функций распределения,
то есть средний модуль разности отсортированных выборок (при равных
размерах) — никакой оптимизации не требуется.

Усреднение по 32 признакам делается ПОСЛЕ приведения каждого к общему
масштабу (медиана и межквартильный размах по всей истории). Без этого сумма
описывала бы признак с наибольшим разбросом, а не расхождение распределений.

## Что эта величина НЕ означает

Она описательна и ничего не предсказывает. Большое расстояние говорит
«сегодняшний рынок непохож на собственную историю» — и ничего не говорит о
том, куда пойдёт цена. Показывать её как предупреждение о движении нельзя.
"""
from __future__ import annotations

import logging

import numpy as np
import pandas as pd

logger = logging.getLogger(__name__)


def robust_scale(frame: pd.DataFrame) -> pd.DataFrame:
    """
    Медиана и IQR по всей истории — тот же приём, что в кластеризации.

    Признак с нулевым IQR (константа на всей истории) остаётся как есть:
    делить на ноль нельзя, а расстояние между двумя одинаковыми константами
    и без нормировки равно нулю.
    """
    median = frame.median()
    iqr = frame.quantile(0.75) - frame.quantile(0.25)
    scale = iqr.where(iqr > 0, 1.0)
    return (frame - median) / scale


def wasserstein_1d(left: np.ndarray, right: np.ndarray) -> float:
    """
    `W₁` между двумя одномерными выборками.

    Считается через квантильную функцию: обе выборки сортируются и
    интерполируются на общую сетку вероятностей, дальше берётся средний
    модуль разности. Это точное значение `W₁` для эмпирических распределений,
    а не приближение: `W₁ = ∫|F⁻¹(p) − G⁻¹(p)| dp`.

    Сетка фиксированной длины (а не объединение обеих выборок) выбрана
    сознательно: окна здесь бывают разной длины, и общая сетка делает
    результат от неё независимым.
    """
    left = np.asarray(left, dtype=float)
    right = np.asarray(right, dtype=float)
    left = left[np.isfinite(left)]
    right = right[np.isfinite(right)]
    if len(left) < 2 or len(right) < 2:
        return float("nan")
    grid = np.linspace(0.0, 1.0, 1001)
    return float(np.mean(np.abs(np.quantile(left, grid) - np.quantile(right, grid))))


def frame_distance(left: pd.DataFrame, right: pd.DataFrame) -> float:
    """Среднее `W₁` по колонкам. Колонки уже обязаны быть приведены к шкале."""
    values = [wasserstein_1d(left[column].to_numpy(), right[column].to_numpy())
              for column in left.columns]
    values = [v for v in values if np.isfinite(v)]
    return float(np.mean(values)) if values else float("nan")


def null_distances(frame: pd.DataFrame, window: int, n_draws: int,
                   rng: np.random.Generator) -> np.ndarray:
    """
    Расстояния между случайными НЕПЕРЕСЕКАЮЩИМИСЯ парами окон длины `window`.

    Непересечение обязательно: два перекрывающихся окна делят наблюдения, и
    расстояние между ними занижено механически. Нулёвка из таких пар сделала
    бы любое реальное расхождение «значимым».

    Пары берутся из ВСЕЙ истории, включая свежую часть. Исключать её было бы
    подгонкой в обратную сторону: вопрос звучит «выделяется ли последний
    квартал среди кварталов вообще», а не «среди старых кварталов».
    """
    n = len(frame)
    if n < 2 * window + 2:
        return np.array([])
    out = []
    attempts = 0
    while len(out) < n_draws and attempts < 20 * n_draws:
        attempts += 1
        a = int(rng.integers(0, n - window))
        b = int(rng.integers(0, n - window))
        if abs(a - b) < window:      # окна пересекаются
            continue
        out.append(frame_distance(frame.iloc[a:a + window],
                                  frame.iloc[b:b + window]))
    return np.array([v for v in out if np.isfinite(v)])


def rolling_drift(frame: pd.DataFrame, window: int, step: int) -> pd.DataFrame:
    """
    Ряд «непохожесть окна на всю предшествующую историю».

    Для каждой точки: расстояние между окном `[t − window, t)` и всей
    историей до него. Это и есть продуктовая величина — «насколько
    сегодняшний рынок непохож на собственное прошлое», по монете.

    История берётся вся, а не окно фиксированной длины: вопрос про «своё
    прошлое», и чем его больше, тем устойчивее опорное распределение.
    """
    rows = []
    for end in range(2 * window, len(frame) + 1, step):
        recent = frame.iloc[end - window:end]
        past = frame.iloc[:end - window]
        rows.append({"ts": frame.index[end - 1],
                     "distance": frame_distance(recent, past)})
    return pd.DataFrame(rows)
