def feature_labels(names: Iterable[str]) -> dict[str, dict[str, str]]:
    """
    Подписи признаков для интерфейса: `{признак: {title, high, low}}`.

    Отдаётся вместе с данными, а не собирается в шаблоне: словарь один на
    проект и живёт здесь. Дубль в JS разъехался бы с именами состояний, и
    панель узла начала бы называть признак иначе, чем подпись самого узла,
    посчитанная из того же признака.
    """
    out: dict[str, dict[str, str]] = {}
    for name in names:
        entry = _VOCABULARY.get(name)
        out[name] = (
            {"title": entry[0], "high": entry[1], "low": entry[2]}
            if entry else {"title": name, "high": "", "low": ""}
        )
    return out


def feature_catalog() -> list[tuple[str, str, str, str, str]]:
    """
    Признаки словаря как плоский список
    `(ось, признак, название, фраза «выше», «ниже»)`.

    Нужен интерфейсу, а не именованию: селектор индикатора на графике
    показывает те же признаки, которыми названы состояния, и в том же порядке
    осей. Второго словаря для этого заводить нельзя — он разъедется с AXES
    молча, и подписи на графике начали бы противоречить именам состояний.
    """
    return [
        (axis, feature, title, positive, negative)
        for axis, vocabulary in AXES
        for feature, (title, positive, negative) in vocabulary.items()
    ]


def describe_state(
    top_features: dict[str, Any] | None,
    dominant_bias: str | None = None,
    max_parts: int = MAX_PARTS,
) -> str:
    """
    Имя состояния по его отклонениям от среднего рынка.

    Из каждой смысловой оси берётся сильнейший признак, оси идут в фиксированном
    порядке, в имя попадают max_parts самых выраженных.

        >>> describe_state({"rv_rank": -0.9, "trend_align": 1.2, "tf1d_rsi": 1.3})
        'затишье · тренд вверх · перекуплен на 1d'
    """
    if not top_features:
        return _BIAS_FALLBACK.get(dominant_bias or "neutral", _BIAS_FALLBACK["neutral"])

    picked: list[tuple[float, int, str]] = []

    for order, (_axis, vocabulary) in enumerate(AXES):
        best_phrase, best_strength = None, 0.0
        for feature, (_title, positive, negative) in vocabulary.items():
            raw = top_features.get(feature)
            if raw is None:
                continue
            try:
                value = float(raw)
            except (TypeError, ValueError):
                continue
            strength = abs(value)
            if strength < SALIENCE or strength <= best_strength:
                continue
            best_phrase, best_strength = (positive if value > 0 else negative), strength
        if best_phrase:
            picked.append((best_strength, order, best_phrase))

    if not picked:
        return _BIAS_FALLBACK.get(dominant_bias or "neutral", _BIAS_FALLBACK["neutral"])

    # Отбираем самые выраженные оси, но выводим в порядке осей, а не силы:
    # «затишье · тренд вверх» читается лучше, чем «тренд вверх · затишье»,
    # и порядок не скачет между соседними состояниями.
    strongest = sorted(picked, key=lambda item: -item[0])[:max_parts]
    return " · ".join(phrase for _s, _o, phrase in sorted(strongest, key=lambda i: i[1]))


def label_for(group_id: float, name: str) -> str:
    """Подпись «номер (имя)» — единый формат для графа, графика и таблиц."""
    return f"{group_id:g} ({name})" if name else f"{group_id:g}"
