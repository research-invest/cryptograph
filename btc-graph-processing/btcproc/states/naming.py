"""
Человекочитаемые имена состояний рынка.

Зачем. `group_id` — это номер кластера, и он не говорит ничего. «Переход 42→1»
читается только если помнить наизусть, чем 42 отличается от 1. Имя вида
«тихий боковик у верха месяца» делает граф и график понятными без сверки
с таблицей признаков.

Почему имя ВЫВОДИТСЯ, а не задаётся руками. `train` перенумеровывает состояния
с нуля при каждом прогоне: состояние 7 прогона #14 и состояние 7 прогона #20 —
разные рынки. Ручной справочник имён протух бы при первом же переобучении,
причём молча: номер остался бы на месте, а подпись стала бы врать. Имя,
посчитанное из статистики самого состояния, разойтись с содержимым не может.

Что на входе. `top_features` из `market_groups` — отклонения средних признаков
группы от общерыночного среднего в стандартных отклонениях (см.
`graph._describe_groups`). Плюс `dominant_bias` как запасной вариант, когда
ни один признак не выделяется.

Имена помонетные по построению: они считаются по признакам конкретной монеты
в конкретном прогоне. Одинаковая формулировка у BTC и ETH означает похожий
режим рынка, но не один и тот же кластер.
"""
from __future__ import annotations

from typing import Any

#: Ниже этого отклонения (в сигмах) признак не считается выделяющимся.
#: 0.5σ — примерно граница, за которой отличие видно глазом на графике;
#: ниже начинается шум, и подпись стала бы вида «чуть-чуть выше среднего».
SALIENCE = 0.5

#: Признаки, сгруппированные по смысловым осям, с формулировками для
#: положительного и отрицательного отклонения.
#:
#: Оси нужны, чтобы имя не превращалось в «перекуплен, перекуплен, перекуплен»:
#: `rsi`, `tf1h_rsi`, `tf4h_rsi` и `tf1d_rsi` — это один и тот же смысл на
#: разных таймфреймах, и в подпись должен попасть только сильнейший из них.
#:
#: Порядок осей = порядок слов в имени: сначала волатильность (она задаёт
#: характер режима), потом направление, потом положение, потом всё остальное.
AXES: tuple[tuple[str, dict[str, tuple[str, str]]], ...] = (
    ("волатильность", {
        # rv_rank / atr_rank — ранг волатильности в месячном окне;
        # range_exp — расширение диапазона бара; rv_ratio — короткая
        # волатильность против длинной.
        "rv_rank":    ("высокая волатильность", "затишье"),
        "atr_rank":   ("широкие бары", "узкие бары"),
        "rv_ratio":   ("всплеск волатильности", "волатильность гаснет"),
        "range_exp":  ("диапазон расширяется", "диапазон сжимается"),
    }),
    ("тренд", {
        # trend_align — расхождение дневной и недельной EMA в ATR:
        # положительное значит дневная выше недельной, тренд согласован вверх.
        "trend_align":   ("тренд вверх", "тренд вниз"),
        "slope_ema_1w":  ("недельный подъём", "недельный спад"),
        "slope_ema_1d":  ("дневной подъём", "дневной спад"),
        "dist_ema_1w":   ("выше недельной средней", "ниже недельной средней"),
        "dist_ema_1d":   ("выше дневной средней", "ниже дневной средней"),
        "tf1d_dist_ema": ("выше средней на 1d", "ниже средней на 1d"),
        "ret_1w":        ("неделя в плюсе", "неделя в минусе"),
        "ret_1d":        ("день в плюсе", "день в минусе"),
    }),
    ("положение", {
        # position_in_range: 0 — низ диапазона окна, 1 — верх.
        "pos_1m":      ("верх месячного диапазона", "низ месячного диапазона"),
        "pos_1w":      ("верх недельного диапазона", "низ недельного диапазона"),
        "pos_1d":      ("верх дневного диапазона", "низ дневного диапазона"),
        "tf1d_pos":    ("верх диапазона 1d", "низ диапазона 1d"),
        "tf4h_pos":    ("верх диапазона 4h", "низ диапазона 4h"),
        # dd_from_high отрицательна по построению (цена ниже максимума),
        # поэтому «менее отрицательная» = у максимума.
        "dd_from_high": ("у максимума", "глубокая просадка"),
    }),
    ("импульс", {
        "rsi":       ("перекуплен", "перепродан"),
        "tf1d_rsi":  ("перекуплен на 1d", "перепродан на 1d"),
        "tf4h_rsi":  ("перекуплен на 4h", "перепродан на 4h"),
        "tf1h_rsi":  ("перекуплен на 1h", "перепродан на 1h"),
        "up_bar_share": ("растущих баров больше", "падающих баров больше"),
        "ret_skew":  ("редкие рывки вверх", "редкие рывки вниз"),
    }),
    ("объём", {
        "vol_z":      ("объём выше обычного", "объём ниже обычного"),
        "vol_ratio":  ("приток объёма", "отток объёма"),
        "taker_bias": ("давят покупатели", "давят продавцы"),
    }),
)

#: Запасные имена, когда ни один признак не дотянул до SALIENCE: состояние
#: близко к «среднему рынку», и сказать про него можно только про исход.
_BIAS_FALLBACK = {
    "long_skew": "невыразительное, чаще рост",
    "short_skew": "невыразительное, чаще падение",
    "neutral": "рынок около среднего",
}

#: Сколько осей попадает в имя. Две-три — предел читаемости в подписи узла
#: графа и в легенде графика; дальше подпись перестаёт помещаться и её
#: перестают читать.
MAX_PARTS = 3


def describe_state(
    top_features: dict[str, Any] | None,
    dominant_bias: str | None = None,
    max_parts: int = MAX_PARTS,
) -> str:
    """
    Имя состояния по его отклонениям от среднего рынка.

    Из каждой смысловой оси берётся сильнейший признак, оси идут в фиксированном
    порядке, в имя попадают max_parts самых выраженных.

        >>> describe_state({"rv_rank": -0.9, "trend_align": 1.2, "tf1d_rsi": 1.3})
        'затишье · тренд вверх · перекуплен на 1d'
    """
    if not top_features:
        return _BIAS_FALLBACK.get(dominant_bias or "neutral", _BIAS_FALLBACK["neutral"])

    picked: list[tuple[float, int, str]] = []

    for order, (_axis, vocabulary) in enumerate(AXES):
        best_phrase, best_strength = None, 0.0
        for feature, (positive, negative) in vocabulary.items():
            raw = top_features.get(feature)
            if raw is None:
                continue
            try:
                value = float(raw)
            except (TypeError, ValueError):
                continue
            strength = abs(value)
            if strength < SALIENCE or strength <= best_strength:
                continue
            best_phrase, best_strength = (positive if value > 0 else negative), strength
        if best_phrase:
            picked.append((best_strength, order, best_phrase))

    if not picked:
        return _BIAS_FALLBACK.get(dominant_bias or "neutral", _BIAS_FALLBACK["neutral"])

    # Отбираем самые выраженные оси, но выводим в порядке осей, а не силы:
    # «затишье · тренд вверх» читается лучше, чем «тренд вверх · затишье»,
    # и порядок не скачет между соседними состояниями.
    strongest = sorted(picked, key=lambda item: -item[0])[:max_parts]
    return " · ".join(phrase for _s, _o, phrase in sorted(strongest, key=lambda i: i[1]))


def label_for(group_id: float, name: str) -> str:
    """Подпись «номер (имя)» — единый формат для графа, графика и таблиц."""
    return f"{group_id:g} ({name})" if name else f"{group_id:g}"
